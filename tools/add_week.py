#!/usr/bin/env python3
"""
Add one week of stock picks to the Markets page.

Usage:
    python3 tools/add_week.py "/path/to/Weekly Picks/2026-11-01"

The week folder holds:
    notes.txt          your scrip notes (format below)
    HDFCBANK.png       screenshots, named by the stock symbol
    HDFCBANK_2.png     (more screenshots for the same stock: add _2, _3 ...)

notes.txt format:
    DATE: 2026-11-01
    SUMMARY: Optional note for the whole week (can run over several lines)

    ### HDFCBANK | NSE | HDFC Bank
    Your note on this stock. Any length, any number of lines.

    ### TATAMOTORS | NSE
    Your note on this stock.

Text is copied exactly as written. Nothing is rewritten or summarised.
Run it again for the same date to replace that week.
"""
import json, os, re, shutil, sys

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PICKS_JS = os.path.join(SITE, "picks", "picks.js")
IMG_EXT = (".png", ".jpg", ".jpeg", ".webp")

HEADER = """/* Weekly stock picks. Generated by tools/add_week.py from your weekly folder.
   Notes are copied exactly as written. Edit by re-running the script for that week. */
window.PICKS = """

def load():
    if not os.path.exists(PICKS_JS):
        return []
    src = open(PICKS_JS, encoding="utf-8").read()
    m = re.search(r"window\.PICKS\s*=\s*(\[.*\])\s*;", src, re.S)
    if not m:
        return []
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S).strip()
    return json.loads(body) if body.strip("[] \n") else []

def parse_notes(text, folder_name):
    text = text.replace("\r\n", "\n").lstrip("﻿")
    parts = re.split(r"^###[ \t]*", text, flags=re.M)
    head, blocks = parts[0], parts[1:]
    date = re.search(r"^DATE:\s*(\d{4}-\d{2}-\d{2})\s*$", head, re.M)
    date = date.group(1) if date else folder_name
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
        sys.exit(f"Could not find a date. Add 'DATE: YYYY-MM-DD' to notes.txt or name the folder YYYY-MM-DD.")
    sm = re.search(r"^SUMMARY:[ \t]*(.*)", head, re.M | re.S)
    summary = sm.group(1).strip() if sm else ""
    stocks = []
    for b in blocks:
        first, _, rest = b.partition("\n")
        bits = [x.strip() for x in first.split("|")]
        if not bits or not bits[0]:
            continue
        stocks.append({
            "symbol": bits[0].upper(),
            "exchange": bits[1].upper() if len(bits) > 1 else "",
            "name": bits[2] if len(bits) > 2 else "",
            "note": rest.strip("\n").rstrip(),
            "images": [],
        })
    if not stocks:
        sys.exit("No stocks found. Start each stock with a line like: ### HDFCBANK | NSE")
    return date, summary, stocks

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    folder = os.path.abspath(sys.argv[1])
    notes = os.path.join(folder, "notes.txt")
    if not os.path.exists(notes):
        sys.exit(f"notes.txt not found in {folder}")
    date, summary, stocks = parse_notes(open(notes, encoding="utf-8").read(), os.path.basename(folder))

    out_dir = os.path.join(SITE, "picks", date)
    if os.path.exists(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)
    files = sorted(f for f in os.listdir(folder) if f.lower().endswith(IMG_EXT))
    unmatched = []
    for f in files:
        stem = os.path.splitext(f)[0].upper()
        base = re.sub(r"[_\- ]\d+$", "", stem)
        match = next((s for s in stocks if s["symbol"] == base), None)
        if not match:
            unmatched.append(f)
            continue
        safe = re.sub(r"[^A-Za-z0-9_.-]", "_", f)
        shutil.copy2(os.path.join(folder, f), os.path.join(out_dir, safe))
        match["images"].append(f"picks/{date}/{safe}")

    weeks = [w for w in load() if w.get("date") != date]
    weeks.append({"date": date, "summary": summary, "stocks": stocks})
    weeks.sort(key=lambda w: w["date"], reverse=True)
    with open(PICKS_JS, "w", encoding="utf-8") as fh:
        fh.write(HEADER + json.dumps(weeks, ensure_ascii=False, indent=2) + ";\n")

    print(f"Added week {date}: {len(stocks)} stocks")
    for s in stocks:
        print(f"  {s['symbol']:<14} {len(s['images'])} screenshot(s)")
    if unmatched:
        print("Not used (file name doesn't match a ### symbol):", ", ".join(unmatched))
    missing = [s["symbol"] for s in stocks if not s["images"]]
    if missing:
        print("No screenshot for:", ", ".join(missing))

if __name__ == "__main__":
    main()
